test('context deletion removes a native pit entry without restoring a phantom switch', async ({ page }) => {
  await start(page, 'Boxenteil entfernen')
  await page.getByTestId('start-pit-create').click()
  await page.getByTestId('pitlane-component-selection').locator('summary').click()
  await page.getByTestId('select-pit-component-pit-entry').click()
  await page.getByTestId('switch-anti-collision').check()
  const canvas = page.getByTestId('graph-track-canvas')
  await canvas.locator('[data-pit-part-id="extra-3"]').click({ button: 'right' })
  await page.getByTestId('context-delete').click()
  await page.getByTestId('planner-save').click()
  const rows = (await (await page.request.get('/api/tracks')).json()).data
  const plan = JSON.parse(rows.find((r) => r.name === 'Boxenteil entfernen').layout)
  expect(plan.pieces[0].type).toBe('Standardgerade')
  expect(plan.trackExtras.filter((e) => e.kind === 'pitEntry')).toHaveLength(1)
  await page.getByTestId('tools-audit').click()
  await page.getByTestId('audit-run').click()
  await expect(page.getByTestId('audit-auxiliary-0')).toBeVisible()
  await page.getByTestId('audit-auxiliary-0').click()
  await expect(page.locator('[data-testid^="audit-auxiliary-mark-"]')).not.toHaveCount(0)
})
