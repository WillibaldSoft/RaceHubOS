import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import { emptyRailInventory, traceTrackPlan } from '../../../packages/shared/src/index.js'
async function start(page, name = 'Bauhilfen') {
  await page.goto('/')
  await page.getByTestId('standalone-new').click()
  await page.locator('.planner-name').fill(name)
}
test('CU can replace an existing straight with undo and without moving neighbours', async ({ page }) => {
  await start(page, 'CU Ersatz')
  await page.getByTestId('add-track-piece').click()
  await page.getByTestId('add-track-piece').click()
  await page.getByTestId('graph-track-canvas').getByTestId('rail-0').click()
  await page.getByTestId('tools-cu').click()
  await expect(page.getByTestId('graph-track-canvas').locator('[data-unit-kind="Control_unit"]')).toHaveCount(1)
  await page.getByTestId('track-undo').click()
  await expect(page.getByTestId('graph-track-canvas').locator('[data-unit-kind="Control_unit"]')).toHaveCount(0)
  await page.getByTestId('track-redo').click()
  await page.getByTestId('planner-save').click()
  const rows = (await (await page.request.get('/api/tracks')).json()).data
  const plan = JSON.parse(rows.find((r) => r.name === 'CU Ersatz').layout)
  expect(plan.pieces.map((p) => p.type)).toEqual(['Control_unit', 'Standardgerade'])
  expect(traceTrackPlan(plan).segments[1].start.x).toBe(345)
})
