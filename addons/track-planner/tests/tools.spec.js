test('assembly templates persist across reload, export, import and insert with undo', async ({ page }) => {
  await start(page)
  await page.getByTestId('start-pit-create').click()
  await page.getByTestId('tools-templates').click()
  await page.getByTestId('template-name').fill('Meine Startbox')
  await page.getByTestId('template-save').click()
  const pending = page.waitForEvent('download')
  await page.getByTestId('template-export').click()
  const download = await pending,
    contents = await fs.readFile(await download.path())
  await page.getByTestId('tools-close').click()
  await page.reload()
  await page.getByTestId('standalone-new').click()
  await page.getByTestId('tools-templates').click()
  await expect(page.getByTestId('template-select')).toContainText('Meine Startbox')
  await page.getByTestId('template-insert').click()
  await expect(page.getByTestId('graph-track-canvas')).toHaveAttribute('data-piece-count', '6')
  await page.getByTestId('track-undo').click()
  await expect(page.getByTestId('graph-track-canvas')).toHaveAttribute('data-piece-count', '0')
  await page.getByTestId('track-redo').click()
  await page.getByTestId('tools-templates').click()
  await page
    .getByTestId('template-import')
    .setInputFiles({ name: 'kaputt.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByTestId('tools-error')).toBeVisible()
  await page
    .getByTestId('template-import')
    .setInputFiles({ name: 'box.json', mimeType: 'application/json', buffer: contents })
  await expect(page.getByTestId('template-select').locator('option')).toHaveCount(2)
  await page.getByTestId('template-delete').click()
  await expect(page.getByTestId('template-select').locator('option')).toHaveCount(1)
})
